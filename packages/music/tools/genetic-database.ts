import {readFile,writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {STYLES,MOTIFS,RHYTHMS,genomeForSKU,GENOME_VERSION} from "../src/genetic-vocabulary.ts";
import {SOUND_COLOURS} from "../src/sound-colours.ts";

const rows=(await readFile(new URL("../../../catalogue/skus.csv",import.meta.url),"utf8")).trim().split(/\r?\n/).slice(1).map(row=>row.split(";"));
const references=rows.map(row=>({sku:Number(row[0]),species:row[2]!,colourName:row[3]!,colour:row[4]!,genome:genomeForSKU(Number(row[0]))}));
const pools=STYLES.map(style=>{
  const candidates=references.filter(reference=>reference.genome.style===style.id);
  const chosen:typeof references=[];
  // Spread botanical examples across the real catalogue; this does not assign instruments by species.
  for(let i=0;i<references.length&&chosen.length<6;i++){
    const reference=references[(i*337+73)%references.length]!;
    if(candidates.includes(reference)&&!chosen.some(item=>item.species===reference.species))chosen.push(reference);
  }
  if(chosen.length<6)throw new Error("Incomplete botanical genome pool");
  return {style:style.id,references:chosen};
});
const database={version:GENOME_VERSION,styles:STYLES,motifs:MOTIFS,rhythms:RHYTHMS,sounds:SOUND_COLOURS,references};
const bytes=JSON.stringify(database);const hash=createHash("sha256").update(bytes).digest("hex");
await writeFile(new URL("../assets/writing-catalogue.json",import.meta.url),bytes+"\n");
await writeFile(new URL("../src/genetic-references.ts",import.meta.url),"// Generated from the real catalogue by tools/genetic-database.ts.\nexport const GENETIC_POOLS = "+JSON.stringify(pools)+" as const;\n");
await writeFile(new URL("../src/genetic-manifest.ts",import.meta.url),"// Generated by tools/genetic-database.ts.\nexport const GENETIC_MANIFEST = "+JSON.stringify({version:GENOME_VERSION,sha256:hash,styles:STYLES.length,motifs:MOTIFS.length,rhythms:RHYTHMS.length,sounds:SOUND_COLOURS.length,references:references.length})+" as const;\n");
console.log(JSON.stringify({sha256:hash,styles:STYLES.length,motifs:MOTIFS.length,rhythms:RHYTHMS.length,sounds:SOUND_COLOURS.length,references:references.length}));
